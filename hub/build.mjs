// Bundles the hub's board page (hub/board.html — the hub's own page; ../planboard.html stays the claude.ai/local page),
// the shim and the overlay into assets.js (strings) so the Worker serves them.
// Runs automatically before `wrangler deploy` (see wrangler.example.jsonc "build"). No dependencies.
import fs from 'node:fs';
const r = (p) => fs.readFileSync(new URL(p, import.meta.url), 'utf8');
const out = `// generated by build.mjs — do not edit\nexport const PAGE = ${JSON.stringify(r('./board.html'))};\nexport const SHIM = ${JSON.stringify(r('../local/pb-local.js'))};\nexport const UI = ${JSON.stringify(r('./hub-ui.js'))};\n`;
fs.writeFileSync(new URL('./assets.js', import.meta.url), out);
console.log('hub/assets.js', Math.round(out.length / 1024), 'KB');
